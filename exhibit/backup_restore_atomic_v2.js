/* RE2-EXH-02: isolated v2 multipart staging + ONE-transaction atomic restore.
 * NOT wired to game/admin. All writes are blocked unless db.name is a fresh
 * gitai-backup-rehearsal-<32 hex> sandbox. Never use with exhibition save DB.
 * Staged parts are temporary. A failed stage is NEVER eligible for a swap.
 * Any quota/abort during the single final readwrite transaction rolls back
 * ALL live object stores together, including current-generation metadata.
 */
(function(root,factory){
  'use strict';
  const api=factory();
  if(typeof module==='object'&&module.exports) module.exports=api;
  else root.GitaiBackupAtomicRestoreV2=api;
})(typeof globalThis==='undefined'?this:globalThis,function(){
  'use strict';
  const STORES=Object.freeze(['images','meta','theater_frames']);
  const STAGE='backup_v2_stage';
  const SANDBOX=/^gitai-backup-rehearsal-[0-9a-f]{32}$/;
  const STAGE_ID=/^restore-[a-f0-9]{32}$/;
  const GEN=/^gen(?:\d{5}|[1-9]\d{5,})$/;
  const fail=message=>{throw Error('分割バックアップ隔離復元：'+message);};
  const validKey=x=>typeof x==='string'||(typeof x==='number'&&Number.isFinite(x));
  const keyRange=id=>IDBKeyRange.bound([id],[id,'\uffff']);
  function requireSandbox(db,stageId) {
    if(!db||!SANDBOX.test(db.name||'')||db.version!==3||
       !STAGE_ID.test(stageId||'')||
       [...STORES,STAGE].some(s=>!db.objectStoreNames?.contains(s))) {
      fail('実験用v3データベース以外には実行できません。');
    }
  }
  function makeStageId(cryptoApi=globalThis.crypto) {
    if(!cryptoApi||typeof cryptoApi.getRandomValues!=='function')
      fail('安全な乱数を取得できません。');
    const bytes=cryptoApi.getRandomValues(new Uint8Array(16));
    return 'restore-'+Array.from(bytes,x=>x.toString(16).padStart(2,'0')).join('');
  }
  function requestCount(db,id) {
    return new Promise((resolve,reject)=>{
      let tx;
      try {
        tx=db.transaction(STAGE,'readonly');
        const req=tx.objectStore(STAGE).count(keyRange(id));
        tx.oncomplete=()=>resolve(req.result);
        tx.onabort=()=>reject(tx.error||Error('Stage count aborted'));
        tx.onerror=()=>{};
      }catch(e){reject(e);}
    });
  }
  function saveBatch(db,id,items) {
    return new Promise((resolve,reject)=>{
      let tx;
      try {
        tx=db.transaction(STAGE,'readwrite');
        tx.oncomplete=resolve;
        tx.onabort=()=>reject(tx.error||Error('Staging aborted'));
        tx.onerror=()=>{};
        const store=tx.objectStore(STAGE);
        for(const record of items){
          if(!STORES.includes(record.store)||!validKey(record.key)||
             !Object.hasOwn(record,'value')||record.value===undefined) {
            tx.abort();
            fail('不正な一時復元項目です。');
          }
          // add() rather than put(): collision cannot silently overwrite
          // another in-progress checkpoint or restored record.
          store.add(record,[id,record.store,record.key]);
        }
      }catch(e){if(tx)try{tx.abort();}catch(_){} reject(e);}
    });
  }
  // Removes only the selected stage ID. Never touches original three stores.
  function discardStage(db,id) {
    requireSandbox(db,id);
    return new Promise((resolve,reject)=>{
      let tx,count=0,early=null;
      try {
        tx=db.transaction(STAGE,'readwrite');
        tx.oncomplete=()=>resolve(count);
        tx.onabort=()=>reject(early||tx.error||Error('Stage cleanup aborted'));
        tx.onerror=()=>{};
        const req=tx.objectStore(STAGE).openCursor(keyRange(id));
        req.onerror=()=>{early=req.error||Error('Stage cleanup cursor error');try{tx.abort();}catch(_){}};
        req.onsuccess=()=>{
          const cursor=req.result;
          if(!cursor)return;
          try{cursor.delete();count++;cursor.continue();}
          catch(e){early=e;try{tx.abort();}catch(_){}}
        };
      }catch(e){if(tx)try{tx.abort();}catch(_){} reject(e);}
    });
  }

  // Proof is generated by the same full semantic preflight as PR #122.
  // A SECOND full hash verification streams decoded items to a TEMPORARY
  // stage, never to the live stores. If a later part fails or quota exhausts,
  // only stage is cleaned. Source records remain untouched.
  async function stageValidatedBackup({
    db,stageId,manifestFile,partFiles,mode,database,partApi,
    semanticApi,checkGenome,checkMothPng,batchSize=16
  }) {
    requireSandbox(db,stageId);
    if(typeof db.name!=='string'||typeof database!=='string'||
       db.name!==database||!partApi||!semanticApi||
       typeof semanticApi.preflightRestore!=='function'||
       typeof semanticApi.decodeValue!=='function'||
       !Number.isSafeInteger(batchSize)||batchSize<1||batchSize>64) {
      fail('復元準備の入力が不正です。');
    }
    // No stage write is even attempted if PNG/DNA or structural checks fail.
    const proof=await semanticApi.preflightRestore({
      manifestFile,partFiles,mode,database,partApi,checkGenome,checkMothPng
    });
    if(!proof.semanticChecked||proof.safeToRestore!==false||
       !GEN.test(proof.generation)||!Number.isSafeInteger(proof.entries)) {
      fail('内容検査の結果が不正です。');
    }
    if(await requestCount(db,stageId)!==0) fail('一時保存IDがすでに使われています。');
    const pending=[];
    const byStore={images:0,meta:0,theater_frames:0};
    let loaded=0;
    try{
      await partApi.verifyPartIntegrity(manifestFile,partFiles,mode,database,
        async (store,key,value)=>{
          pending.push({store,key,value:semanticApi.decodeValue(value)});
          byStore[store]++;
          loaded++;
          if(pending.length>=batchSize) {
            await saveBatch(db,stageId,pending);
            pending.length=0;
          }
        });
      if(pending.length) await saveBatch(db,stageId,pending);
      if(loaded!==proof.entries||(await requestCount(db,stageId))!==loaded)
        fail('一時保存件数が事前検証と一致しません。');
      return Object.freeze({
        stageId,mode,database,generation:proof.generation,
        entries:loaded,byStore:Object.freeze(byStore),stageComplete:true,
        // No commit has occurred yet; warning life is NOT restored.
        lifeRestored:false
      });
    }catch(error){
      try{await discardStage(db,stageId);}
      catch(cleanup){error.cleanupError=cleanup;}
      throw error;
    }
  }

  // Final swap: count stage, clear 3 stores, copy cursor entries, rotate
  // restore_epoch, all within ONE readwrite transaction spanning all 4 stores.
  // Any malformed/incomplete stage or failed PUT aborts and rolls back clear().
  // Never await file/Blob conversion or any promise within this transaction.
  async function commitStagedRestore(db,prepared,{cryptoApi=globalThis.crypto}={}){
    if(!prepared||prepared.stageComplete!==true)
      fail('検証と一時保存が完了していません。');
    requireSandbox(db,prepared.stageId);
    if(prepared.database!==db.name||!GEN.test(prepared.generation)||
       !Number.isSafeInteger(prepared.entries)||prepared.entries<121||
       !prepared.byStore||STORES.some(s=>
         !Number.isSafeInteger(prepared.byStore[s])||prepared.byStore[s]<0)||
       STORES.reduce((sum,s)=>sum+prepared.byStore[s],0)!==prepared.entries) {
      fail('一時保存の検証結果が不正です。');
    }
    const random=makeStageId(cryptoApi);
    const epoch='restore-'+random.slice('restore-'.length);
    const result=await new Promise((resolve,reject)=>{
      let tx,early=null;
      let seen=0,pointer=false;
      const counts={images:0,meta:0,theater_frames:0};
      const images=new Set(),genomes=new Set();
      function abort(error){
        if(!early)early=error;
        try{tx.abort();}catch(_){}
      }
      try{
        tx=db.transaction([...STORES,STAGE],'readwrite');
        tx.oncomplete=()=>resolve({generation:prepared.generation,entries:seen,epoch});
        tx.onabort=()=>reject(early||tx.error||Error('Atomic restore rolled back'));
        tx.onerror=()=>{};
        const stage=tx.objectStore(STAGE);
        const req=stage.count(keyRange(prepared.stageId));
        req.onerror=()=>abort(req.error||Error('Stage count failed'));
        req.onsuccess=()=>{
          if(req.result!==prepared.entries) {
            abort(Error('Incomplete restore stage; originals preserved'));return;
          }
          try {
            for(const name of STORES) tx.objectStore(name).clear();
            const cursorReq=stage.openCursor(keyRange(prepared.stageId));
            cursorReq.onerror=()=>abort(cursorReq.error||Error('Stage cursor failed'));
            cursorReq.onsuccess=()=>{
              if(early)return;
              const cursor=cursorReq.result;
              if(!cursor) {
                if(seen!==prepared.entries||!pointer||
                   STORES.some(s=>counts[s]!==prepared.byStore[s])||
                   images.size!==60||genomes.size!==60) {
                  abort(Error('Incomplete staged genome/images; originals preserved'));
                  return;
                }
                // A backup's old restore_epoch is overwritten last.
                try{tx.objectStore('meta').put(epoch,'restore_epoch');}
                catch(e){abort(e);}
                return;
              }
              const k=cursor.key,rec=cursor.value;
              if(!Array.isArray(k)||k.length!==3||k[0]!==prepared.stageId||
                 !STORES.includes(k[1])||!rec||rec.store!==k[1]||
                 !validKey(k[2])||rec.key!==k[2]||
                 !Object.hasOwn(rec,'value')) {
                abort(Error('Staged restore row is corrupt'));return;
              }
              try {
                tx.objectStore(rec.store).put(rec.value,rec.key);
                counts[rec.store]++;seen++;
                if(rec.store==='meta'&&rec.key==='current_generation_id') {
                  if(rec.value!==prepared.generation) {
                    abort(Error('Stage generation mismatch'));return;
                  }
                  pointer=true;
                }
                if(rec.store==='images'&&typeof rec.key==='string'&&
                   rec.key.startsWith(prepared.generation+':'))
                  images.add(rec.key);
                if(rec.store==='meta'&&typeof rec.key==='string'&&
                   rec.key.startsWith('genome:'+prepared.generation+':'))
                  genomes.add(rec.key);
                if(seen>prepared.entries) {
                  abort(Error('Unexpected extra stage record'));return;
                }
                cursor.continue();
              }catch(e){abort(e);}
            };
          }catch(e){abort(e);}
        };
      }catch(e) {
        if(tx){early=e;try{tx.abort();}catch(_){reject(e);}}
        else reject(e);
      }
    });
    let cleanupError=null;
    try{await discardStage(db,prepared.stageId);}
    catch(error){cleanupError=error?.message||String(error);}
    return Object.freeze({
      status:cleanupError?'db-committed-cleanup-warning':'db-committed',
      generation:result.generation,entries:result.entries,
      epoch:result.epoch,lifeRestored:false,
      cleanupError
    });
  }

  return Object.freeze({STORES,STAGE,makeStageId,
    stageValidatedBackup,commitStagedRestore,discardStage});
});
